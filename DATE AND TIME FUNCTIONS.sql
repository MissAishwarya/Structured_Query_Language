USE SalesDB

SELECT * FROM SALES.Orders

SELECT
OrderDate,ShipDate,CreationTime
FROM
SALES.Orders

/*Three ways to create dates
First which is available in the source
second is hard coded
third is GETDATE()*/

SELECT
ORDERDATE,
'2026-08-08' AS HARDCODED,
GETDATE() AS TODAY
FROM SALES.Orders

---DAY
---MONTH
---YEAR

SELECT
CreationTime,YEAR(CREATIONTIME) AS YEAR,MONTH(CREATIONTIME) AS MONTH,DAY(CREATIONTIME) AS DAY
FROM
SALES.Orders

--DATEPART->WEEK,QUARTER,MONTH WHAT PART AND FROM WHERE JUST TWO ARGUMENTS
SELECT
DATEPART(MONTH,CREATIONTIME) AS MONTH_DP,
DATEPART(YEAR,CREATIONTIME) AS YEAR_DP,
DATEPART(QUARTER,CREATIONTIME) AS QUARTER_DP,
DATEPART(DAY,CREATIONTIME) AS DAY_DP,
DATEPART(WEEK,CREATIONTIME) AS WEEK_DP
FROM SALES.Orders

---DATENAME GIVES THE NAME
SELECT 
DATENAME(MONTH,CreationTime) as MONTH_NAME,
DATENAME(QUARTER,CREATIONTIME) AS QUARTER_NAME,
DATENAME(WEEKDAY,CREATIONTIME) AS DAY_NAME
FROM SALES.ORDERS

---DATETRUNC
SELECT
DATETRUNC(MONTH,CreationTime) AS MONTH_TC,
COUNT(*)
FROM SALES.Orders
GROUP BY DATETRUNC(MONTH,CreationTime)]

---Till Month part everything will be same rest after that part all will reset to the starting values
SELECT
CREATIONTIME,
DATETRUNC(MONTH,CREATIONTIME)
FROM SALES.Orders

select
DATETRUNC(YEAR,CREATIONTIME),
COUNT(*)
FROM SALES.ORDERS
GROUP BY DATETRUNC(YEAR,CREATIONTIME)

---EOMONTH
SELECT EOMONTH(CREATIONTIME)
FROM SALES.ORDERS

SELECT EOMONTH(CREATIONTIME) AS END_OF_MONTH,
CAST(DATETRUNC(MONTH,CREATIONTIME) AS DATE) AS START_OF_MONTH
FROM SALES.ORDERS

---How many orders were placed each year
SELECT * FROM SALES.ORDERS

SELECT
DATEPART(YEAR,DATETRUNC(YEAR,ORDERDATE)) AS YEAR,COUNT(*) AS COUNT_OF_ORDERS
FROM SALES.ORDERS
GROUP BY DATEPART(YEAR,DATETRUNC(YEAR,ORDERDATE))

---How many orders were placed each month
SELECT
DATENAME(MONTH,DATETRUNC(MONTH,ORDERDATE)) AS MONTH_NAME,
COUNT(*) AS COUNT_OF_ORDERS
FROM SALES.ORDERS
GROUP BY DATENAME(MONTH,DATETRUNC(MONTH,ORDERDATE))	

--Show all the orders that were placed during the month of February
SELECT * FROM SALES.ORDERS
WHERE MONTH(ORDERDATE)=2

--BEST PRACTICE-FILTERING DATA USING AN INTEGER IS FASTER THEN USING A STRING

/*FORMAT AND CASTING
MM-MONTH
mm-minutes
YYYY-MM-dd  INternational Standard(ISO 8601)
MM-dd-YYYY   USA Standard
dd-MM-YYYY   EUROPEAN STANDARD

Formatting-Changing the value from one to another
Same like TEXT function in Excel

There is another function which is CONVERT where there are styles to be assigned
FORMAT

CAST is used to change the DATATYPE
For example String to Date datatype
*/


SELECT
CreationTime,
FORMAT(CREATIONTIME,'dd') as DD,
FORMAT(CREATIONTIME,'ddd') AS DDD,
FORMAT(CREATIONTIME,'dddd') AS DDDD,
FORMAT(CREATIONTIME,'MM') AS MM,
FORMAT(CREATIONTIME,'MMM') AS MMM
FROM SALES.Orders

SELECT * FROM SALES.Orders
--DAY WED JAN Q1 2025 12:34:56 PM
SELECT
CREATIONTIME,
CONCAT(FORMAT(CREATIONTIME,'dd'),' ',FORMAT(CREATIONTIME,'ddd'),' ',FORMAT(CREATIONTIME,'MMM'),' ','Q',datepart(QUARTER,CREATIONTIME),
' ',FORMAT(CREATIONTIME,'yyyy'),' ',FORMAT(CREATIONTIME,'hh:mm:ss tt'))
FROM SALES.Orders

SELECT
FORMAT(ORDERDATE,'MMM yy') AS MONTH_YEAR,
COUNT(*) AS COUNT
FROM SALES.Orders
GROUP BY FORMAT(OrderDate,'MMM yy')

---FORMATTING USE CASE- DATA STANDARDIZATION
/*CONVERT - Converts a date or time value to a different data type and FORMATS the value*/

SELECT
CREATIONTIME,
FORMAT(DATETRUNC(MONTH,CREATIONTIME),'dd-MM-yyyy') AS [START OF MONTH],
FORMAT(EOMONTH(CREATIONTIME),'dd-MM-yyyy') AS [END OF MONTH]
FROM SALES.ORDERS


