USE SalesDB

USE MyDatabase 
---Show a List of customers first names together with their country in one column
SELECT *
FROM customers

SELECT
first_name,country, CONCAT(FIRST_NAME,' ',COUNTRY) AS NAME_COUNTRY
FROM customers 

--Convert first name to lowercase AND Uppercase

SELECT
FIRST_NAME,LOWER(FIRST_NAME) AS LOWERCASE, UPPER(FIRST_NAME) AS UPPERCASE
FROM customers 

---TRIM the Data
select 
FIRST_NAME,TRIM(FIRST_NAME) AS TRIMMED_COL, LEN(FIRST_NAME) AS INITIAL, LEN(TRIM(FIRST_NAME)) AS FINAL,LEN(FIRST_NAME)-LEN(TRIM(FIRST_NAME)) 
AS FLAG
FROM customers
WHERE LEN(FIRST_NAME)-LEN(TRIM(FIRST_NAME))>0

