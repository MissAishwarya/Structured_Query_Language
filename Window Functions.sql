use salesdb

select * from sales.Orders

SELECT SUM(SALES) FROM SALES.ORDERS

SELECT PRODUCTID,SUM(SALES) 
FROM SALES.ORDERS
GROUP BY PRODUCTID

---Find the total sales for each product,additionally provide details such order id and order date
---Cannot do aggregations and provide details at same time
SELECT
OrderID,OrderDate,ProductID,SUM(SALES)
FROM
SALES.ORDERS
GROUP BY OrderID,OrderDate,ProductID

--rESULT GRANULARITY-WINDOW FUNCTIONS RETURNS A RESULT FOR EACH ROW
SELECT
PRODUCTID,
ORDERID,
ORDERDATE,
sum(Sales) over(PARTITION BY PRODUCTID)
FROM
SALES.ORDERS

---PARTITION BY IS SAME AS GROUP BY
---TO SHOW AGGREGATIONS AND ADDITIONAL INFORMATION AS ANALYTICS GETS HARDER
SELECT * FROM SALES.Orders

SELECT
ORDERID,
ORDERDATE,
SUM(SALES) OVER() TOTALSALES
FROM SALES.ORDERS

----TOTAL SALES FOR EACH PRODUCT ADDITIONALLY PROVIDE DETAILS SUCH AS ORDER ID AND ORDER DATE
SELECT
ORDERID,
ORDERDATE,
SUM(sALES) OVER(PARTITION BY PRODUCTID) TOTALSALES
FROM SALES.ORDERS

---Flexibility of window - allows aggregation of data at different granularities within the same query
SELECT
*,
SUM(SALES) OVER() AS TOTALSALES,
SUM(sALES) OVER(PARTITION BY PRODUCTID) AS TOTALSALESBYPID
FROM SALES.ORDERS

--Find Total Sales for each combination of product and order status
SELECT 
SUM(SALES) OVER(PARTITION BY PRODUCTID,ORDERSTATUS) AS TOTALSALES
FROM SALES.ORDERS

---Rank each order based on their sales from highest to lowest
---additionally provide details such as order id and order date

SELECT
SALES,
RANK() OVER(ORDER BY SALES) AS [RANK SALES]
FROM SALES.ORDERS

